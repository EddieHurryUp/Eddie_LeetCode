"""
阿里算法笔试 - 第二题（ACM 模式）题目总结

题意：
有一个 n x m 的棋盘，记第 i 行第 j 列为 a[i][j]，字符仅为 '0' 或 '1'。
棋盘上有且仅有一个棋子，初始在左上角 (1,1)。

两名同学轮流操作：天才同学先手，笨蛋同学后手。
每次操作必须将棋子从当前位置移动一步：
- 向右，或
- 向下
若某方向越界，则该方向不可选。

移动后按“新到达格子”计分：
- 若该格子是 '1'，当前操作方记 +1 分；
- 若该格子是 '0'，当前操作方记 -1 分。
注意：初始格子 (1,1) 不计分。

当棋子到达右下角 (n,m) 时，游戏立即结束。

目标：
在双方都采取最优策略时，计算：
    天才同学总分 - 笨蛋同学总分

输入格式：
- 第一行输入两个整数 n, m
  1 <= n, m <= 2 * 10^5，且 n * m <= 4 * 10^5
- 接下来 n 行，每行一个长度为 m 的字符串，仅包含 '0' 和 '1'

输出格式：
- 输出一个整数，表示最优博弈下（天才总分 - 笨蛋总分）的差值。

示例 1：
输入：
2 2
01
11

输出：
0

示例 2：
输入：
1 3
101

输出：
-2
"""

# 后续可在本文件继续补：
# 1) 状态定义（博弈 DP / 极大极小）
# 2) 转移方程与先后手判定
# 3) ACM 可提交代码（注意 O(n*m) 与内存优化）

import sys
n, m = map(int, sys.stdin.readline().split())

g = [sys.stdin.readline().strip() for _ in range(n)]

dp = [[0] * m for _ in range(n)]
dp[n-1][m-1] = 0

for i in range(n-1, -1, -1):
    for j in range(m-1, -1, -1):
        if i == n-1 and j == m-1:
            continue
        is_tiancai = ((i+j)%2== 0)

        cand = []

        # down
        if i + 1 < n:
            v = 1 if g[i+1][j] == '1' else -1
            if is_tiancai:
                cand.append(v + dp[i+1][j])
            else:
                cand.append(-v + dp[i+1][j])
        # right
        if j + 1 < m:
            v = 1 if g[i][j+1] == '1' else -1
            if is_tiancai:
                cand.append(v + dp[i][j+1])
            else:
                cand.append(-v + dp[i][j+1])
        if is_tiancai:
            dp[i][j] = max(cand)
        else:
            dp[i][j] = min(cand)
print(dp[0][0])

# -------------------- 思考过程与结果总结 --------------------
# 1) 看到“双方都最优策略” -> 这是一个零和博弈（天才想让差值最大，笨蛋想让差值最小）。
# 2) 看到“每次只能向右/向下” -> 状态图无环，可用倒推 DP（minimax）。
# 3) 定义 dp[i][j]：
#    棋子在 (i,j) 且从这里开始双方最优时，最终 (天才总分 - 笨蛋总分) 的最优差值。
# 4) 终点 (n-1,m-1) 无后续移动，dp[n-1][m-1] = 0。
# 5) 谁行动由 (i+j) 奇偶决定：
#    - (i+j) 为偶：轮到天才，取 max；
#    - (i+j) 为奇：轮到笨蛋，取 min。
# 6) 走到新格子的得分 v（'1'->+1, '0'->-1）对差值影响：
#    - 天才走：+v
#    - 笨蛋走：-v
#    再加上后续状态 dp[next]，构成转移。
#
# 最终结果：
# - 答案就是 dp[0][0]，表示从起点开始的最优博弈分差。
# - 虽然最优路径可能不唯一，但“最优博弈值（分差）”是唯一的。
# - 时间复杂度 O(n*m)，空间复杂度 O(n*m)。
